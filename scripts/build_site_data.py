"""Build docs/data.js for the GitHub Pages site from the saved results.

Every number on the web page comes from this file, and this file only
reads what training wrote to reports/ plus the saved model. Nothing is typed in by hand.

Usage:  python scripts/build_site_data.py
"""

import json
from datetime import date

import pandas as pd

from turbofan_rul.config import RISK_HIGH, RISK_MEDIUM, ROOT, RUL_CAP, SENSOR_NAMES
from turbofan_rul.data import load_test
from turbofan_rul.explain import template_note
from turbofan_rul.features import build_features
from turbofan_rul.model import RULModel, risk_level

REPORTS = ROOT / "reports"
OUT = ROOT / "docs" / "data.js"
TRAJECTORY_ENGINE = 49   # the test engine with the longest history (303 cycles)
EXAMPLE_ENGINE = 31      # used for the "explain this prediction" example


def main() -> None:
    metrics = json.loads((REPORTS / "metrics.json").read_text())
    preds = pd.read_csv(REPORTS / "test_predictions.csv")
    attr = pd.read_csv(REPORTS / "test_attributions.csv")
    model = RULModel.load()
    test, truth = load_test()

    # Global importance = average size of each sensor's what-if impact over the 100 test engines.
    importance = (
        attr.assign(abs_impact=attr["impact_cycles"].abs())
        .groupby(["feature", "description"], as_index=False)["abs_impact"].mean()
        .sort_values("abs_impact", ascending=False)
    )

    # Prediction at every cycle of one engine (features only use the past, so this
    # is what the model would have said live at each point).
    eng = test[test["unit"] == TRAJECTORY_ENGINE]
    feats = build_features(eng, model.sensors)
    traj_pred = model.predict_features(feats[model.feature_cols])
    true_at_end = float(truth[TRAJECTORY_ENGINE - 1])
    traj_true = true_at_end + eng["cycle"].max() - eng["cycle"]

    # Explanation example (template note, so it's reproducible without Ollama).
    ex = test[test["unit"] == EXAMPLE_ENGINE]
    x = model.latest_features(ex)
    ex_rul = float(model.predict_features(x)[0])
    ex_factors = model.explain_features(x)
    ex_note = template_note(f"FD001-test-{EXAMPLE_ENGINE}", ex_rul, risk_level(ex_rul), ex_factors)

    risk_counts = pd.crosstab(preds["risk_true"], preds["risk_predicted"]).reindex(
        index=["high", "medium", "low"], columns=["high", "medium", "low"], fill_value=0
    )

    data = {
        "built": date.today().isoformat(),
        "meta": {
            "subset": metrics["subset"],
            "trainEngines": metrics["n_train_engines"],
            "trainRows": metrics["n_train_rows"],
            "testEngines": metrics["n_test_engines"],
            "testRows": metrics["n_test_rows"],
            "rulCap": RUL_CAP,
            "nFeatures": metrics["n_features"],
            "sensorsUsed": metrics["sensors_used"],
            "sensorsDropped": metrics["sensors_dropped"],
            "selectedModel": metrics["selected_model"],
            "riskHigh": RISK_HIGH,
            "riskMedium": RISK_MEDIUM,
        },
        "models": [
            {
                "run": m["run"],
                "family": m["family"],
                "cvRmse": round(m["cv_rmse"], 2),
                "testRmse": round(m["test_rmse"], 2),
                "nasa": round(m["test_nasa_score"], 3),
            }
            for m in metrics["models"]
        ],
        "final": {k: round(v, 4) for k, v in metrics["final"].items()},
        "engines": preds.to_dict(orient="list"),
        "importance": {
            "sensor": importance["feature"].tolist(),
            "label": importance["description"].tolist(),
            "cycles": importance["abs_impact"].round(2).tolist(),
        },
        "trajectory": {
            "engine": TRAJECTORY_ENGINE,
            "cycle": eng["cycle"].tolist(),
            "predicted": [round(float(v), 2) for v in traj_pred],
            "true": [float(v) for v in traj_true],
        },
        "riskMatrix": {"order": ["high", "medium", "low"], "counts": risk_counts.to_numpy().tolist()},
        "example": {
            "engine": EXAMPLE_ENGINE,
            "predicted": round(ex_rul, 1),
            "true": float(truth[EXAMPLE_ENGINE - 1]),
            "risk": risk_level(ex_rul),
            "factors": [
                {"sensor": f["feature"], "label": f["description"], "impact": f["impact_cycles"]}
                for f in ex_factors[:5]
            ],
            "note": ex_note,
        },
        "sensorNames": SENSOR_NAMES,
    }
    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text("// Generated by scripts/build_site_data.py - don't edit by hand.\nwindow.RUL_DATA = "
                   + json.dumps(data, separators=(",", ":")) + ";\n")
    print(f"Wrote {OUT} ({OUT.stat().st_size / 1024:.0f} KB)")


if __name__ == "__main__":
    main()
